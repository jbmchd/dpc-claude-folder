--  mais a coluna, a FK2 e o indice IX2 em dpc_dfe_manifestacao
-- ===========================================================================

select 'tabela' tipo, table_name nome, to_char(null) detalhe
  from all_tables
 where owner = 'POSEIDON' and table_name = 'DPC_DFE_MANIF_PEDIDO'
union all
select 'coluna', column_name, data_type
  from all_tab_columns
 where owner = 'POSEIDON' and table_name = 'DPC_DFE_MANIF_PEDIDO'
union all
select 'coluna nova', column_name, data_type
  from all_tab_columns
 where owner = 'POSEIDON' and table_name = 'DPC_DFE_MANIFESTACAO'
   and column_name = 'COD_DFE_MANIF_PEDIDO'
union all
select 'constraint', constraint_name, constraint_type
  from all_constraints
 where owner = 'POSEIDON'
   and constraint_name in ('DPC_DFE_MANIF_PEDIDO_PK', 'DPC_DFE_MANIF_PEDIDO_CK1',
                           'DPC_DFE_MANIF_PEDIDO_CK2', 'DPC_DFE_MANIF_FK2')
union all
select 'indice', index_name, status
  from all_indexes
 where owner = 'POSEIDON' and index_name = 'DPC_DFE_MANIF_IX2'
 order by 1, 2;
