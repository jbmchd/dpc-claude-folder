-- ============================================================================
--  MODULO DFe - ESTRUTURA DAS TELAS (ddl/02_estrutura_telas)
-- ============================================================================
--  As seis tabelas que o BLOCO DE TELAS usa: quem ve o que, as colunas e os modelos de cada usuario, a permissao
--  de manifestar e o limiar de dias do painel de alerta.
--
--      dpc_dfe_usuario_empresa     quais filiais o usuario ve
--      dpc_dfe_usuario_aba         quais categorias o usuario ve (DEVOLUCAO, COMPRAS, SUPRIMENTOS,
--                                  SEM_CLASSIFICACAO, PROPRIAS)
--      dpc_dfe_usuario_permissao   permissoes de acao (MANIFESTAR)
--      dpc_dfe_usuario_coluna      colunas escolhidas na tela, guardadas no servidor
--      dpc_dfe_usuario_modelo      modelos nomeados de filtro e de colunas (JSON em CLOB)
--      dpc_dfe_painel_alerta       a partir de quantos dias a nota pendente aparece como atrasada
--
--  MOTOR x TELAS: o motor e CLI e banco, sem sessao e sem login; qualquer tabela com "usuario" no nome, dentro
--  do modulo, e de tela. Por isso o motor nao leva rotulo no nome e as telas sao um arquivo a parte.
--
--  Consolida, em 13/10/2026, o antigo 03_01 e os blocos 04_02, 06_01, 10_01, 11_01 e 14_01. Convergente como o
--  01_estrutura_motor: serve a base vazia, parcial ou completa; reexecutar nao muda nada.
--
--  ==========================================================================
--   O QUE ESTE ARQUIVO CARREGA DE DECISAO
--  ==========================================================================
--   - A PK ID e IDENTITY (generated by default as identity), e nao trigger + sequence: trocar mudaria o contrato
--     dos repositorios que fazem insert, e permite copiar com as mesmas chaves. 43 das 1.098 tabelas do schema
--     ja usam identity.
--   - NOME DE COLUNA fora da convencao (id, nroempresa, usuario, dias, cor_no_periodo): fica como esta,
--     porque cor_no_periodo e cor_fora_periodo sao lidas PELO NOME no front e nroempresa e o nome do banco
--     legado em 237 arquivos do DPC.
--   - Permissao ausente = tela vazia SEM erro (o repositorio curto-circuita com HTTP 200 e lista vazia).
--     Por isso uma aba nova exige DDL (a CHECK da aba tem lista fechada) E permissao concedida.
--   - As tabelas de tela sao COPIADAS UMA VEZ pelo dfe:replicar na carga inicial e, depois, pertencem a
--     producao: o comando nao toca em tabela de tela que ja tem dado.
--
--  ==========================================================================
--   COMO RODAR (DBeaver)
--  ==========================================================================
--  Conectado como POSEIDON, arquivo INTEIRO com Alt+X. Sem "/" para terminar bloco. E CRLF de proposito: em LF
--  o divisor de statements do DBeaver corta o bloco PL/SQL no fim do IF e devolve PLS-00103. Nenhum bloco tem
--  linha em branco dentro (o DBeaver trata linha em branco como fim de statement).
--
--  LIGUE O DBMS_OUTPUT (aba Output do editor de SQL): a secao 3 avisa por ali o que acrescentou e o que exige
--  decisao humana; sem o Output ligado esses avisos passam invisiveis.
--
--  Se algo falhar no meio, corrija e rode o arquivo de novo - o que ja passou nao e refeito nem duplicado.
-- ============================================================================


