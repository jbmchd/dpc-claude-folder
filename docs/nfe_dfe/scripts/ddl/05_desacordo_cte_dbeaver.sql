declare
  qtd number;
begin
  select count(*) into qtd from all_constraints
   where owner = 'POSEIDON' and constraint_name = 'DPC_DFE_CTE_DESACORDO_FK1';
  if qtd = 0 then
    execute immediate q'[alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_FK1 foreign key (cod_dfe_cte) references poseidon.dpc_dfe_cte (cod_dfe_cte)]';
  end if;
end;
/

declare
  v_cond varchar2(4000);
begin
  select search_condition_vc into v_cond from all_constraints
   where owner = 'POSEIDON' and constraint_name = 'DPC_DFE_CTE_DESACORDO_CK1';
  if lower(regexp_replace(v_cond, '[[:space:]]', '')) <> q'[status_envioin('E','F')]' then
    execute immediate 'alter table poseidon.dpc_dfe_cte_desacordo drop constraint DPC_DFE_CTE_DESACORDO_CK1';
    execute immediate q'[alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_CK1 check (status_envio in ('E', 'F'))]';
    dbms_output.put_line('DPC_DFE_CTE_DESACORDO_CK1: redefinida');
  end if;
exception
  when no_data_found then
    execute immediate q'[alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_CK1 check (status_envio in ('E', 'F'))]';
end;
/

