--  1) INVARIANTES deste arquivo. ESPERADO: as quatro linhas com qtd = 0.
select 'coluna sem comentario'  as invariante, count(*) as qtd
  from all_tab_columns c
 where c.owner = 'POSEIDON' and (c.table_name = 'DPC_DFE_USUARIO_EMPRESA' or c.table_name = 'DPC_DFE_USUARIO_ABA' or c.table_name = 'DPC_DFE_USUARIO_PERMISSAO' or c.table_name = 'DPC_DFE_USUARIO_COLUNA' or c.table_name = 'DPC_DFE_USUARIO_MODELO' or c.table_name = 'DPC_DFE_PAINEL_ALERTA')
   and not exists (select 1 from all_col_comments m
                    where m.owner = c.owner and m.table_name = c.table_name
                      and m.column_name = c.column_name and m.comments is not null)
union all
select 'tabela ausente', count(*) from (
  select column_value as tabela from table(sys.odcivarchar2list('DPC_DFE_USUARIO_EMPRESA', 'DPC_DFE_USUARIO_ABA', 'DPC_DFE_USUARIO_PERMISSAO', 'DPC_DFE_USUARIO_COLUNA', 'DPC_DFE_USUARIO_MODELO', 'DPC_DFE_PAINEL_ALERTA'))
   minus select table_name from all_tables where owner = 'POSEIDON')
union all
select 'tabela sem PK', count(*)
  from all_tables t
 where t.owner = 'POSEIDON' and (t.table_name = 'DPC_DFE_USUARIO_EMPRESA' or t.table_name = 'DPC_DFE_USUARIO_ABA' or t.table_name = 'DPC_DFE_USUARIO_PERMISSAO' or t.table_name = 'DPC_DFE_USUARIO_COLUNA' or t.table_name = 'DPC_DFE_USUARIO_MODELO' or t.table_name = 'DPC_DFE_PAINEL_ALERTA')
   and not exists (select 1 from all_constraints k
                    where k.owner = t.owner and k.table_name = t.table_name and k.constraint_type = 'P')
union all
select 'objeto invalido', count(*)
  from all_objects
 where owner = 'POSEIDON' and object_name like '%DFE%' and status <> 'VALID';

