-- ============================================================================
--  SECAO 4 - CONFERENCIA
-- ============================================================================
select 'coluna' as tipo, column_name as objeto,
       data_type || '(' || data_length || ')' as detalhe,
       nullable as obs
  from all_tab_columns
 where owner = 'POSEIDON' and table_name = 'DPC_DFE_EMPRESA'
   and column_name = 'DTA_INICIO_MANIF_AUTO_CONF'
union all
select 'tabela', table_name, 'existe', null
  from all_tables
 where owner = 'POSEIDON' and table_name = 'DPC_DFE_USUARIO_PERMISSAO'
union all
select 'constraint', c.constraint_name,
       listagg(cc.column_name, ',') within group (order by cc.position), c.constraint_type
  from all_constraints c
  join all_cons_columns cc on cc.owner = c.owner and cc.constraint_name = c.constraint_name
 where c.owner = 'POSEIDON'
   and c.constraint_name in ('DPC_DFE_USUARIO_PERMISSAO_PK','DPC_DFE_USUARIO_PERMISSAO_UK1','DPC_DFE_USUARIO_PERMISSAO_CK1')
 group by c.constraint_name, c.constraint_type
 order by 1, 2;
