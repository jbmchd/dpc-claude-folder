-- ============================================================================
--  MODULO DFe - INSTALADOR 05: DESACORDO DO CT-e (poseidon.dpc_dfe_cte_desacordo)
-- ============================================================================
--  Uma tabela, convergente como os instaladores 01 e 02: roda quantas vezes quiser. Cria a tabela se faltar,
--  acrescenta a coluna que faltar e redefine o CHECK cuja definicao mudou.
--
--  O QUE GUARDA: cada tentativa de "Prestacao do Servico em Desacordo" (evento 610110) enviada a SEFAZ pela tela de
--  CT-e: quem mandou, a justificativa, e o que a SEFAZ respondeu (cStat, motivo, protocolo). E trilha de AUDITORIA de
--  um ato fiscal; o evento em si volta depois pela distribuicao e entra em dpc_dfe_cte_evento como qualquer outro.
--    status_envio  E = SEFAZ registrou (cStat 135/136)  |  F = recusado ou falhou (o motivo fica na linha)
--
--  POR QUE ARQUIVO PROPRIO: o 01 e o instalador GERADO das 17 tabelas do motor e tem uma secao por tipo de objeto
--  (tabelas, colunas, constraints, indices, comentarios...). Uma tabela nova nasce aqui, inteira num lugar so, sem
--  mexer no gerado. Roda depois do 01 (a FK aponta para dpc_dfe_cte).
--
--  QUEM RODA E ONDE: homolog primeiro; em producao so com ordem do Joabe / pelo Douglas, ANTES do deploy da ApiNFE que
--  traz o endpoint de desacordo (sem a tabela o endpoint falha ao gravar a trilha). Conectado como POSEIDON, o script
--  inteiro (Alt+X no DBeaver). Desfazer: rollback/05_99_rollback_desacordo_cte_dbeaver.sql.
-- ============================================================================

-- ---------- TABELA ----------
declare
  qtd number;
begin
  select count(*) into qtd from all_tables
   where owner = 'POSEIDON' and table_name = 'DPC_DFE_CTE_DESACORDO';
  if qtd = 0 then
    execute immediate q'[create table poseidon.dpc_dfe_cte_desacordo
        (
          cod_dfe_cte_desacordo      NUMBER generated by default as identity not null,
          cod_dfe_cte                NUMBER not null,
          chave_cte                  VARCHAR2(44) not null,
          usuario                    VARCHAR2(100) not null,
          dsc_justificativa          VARCHAR2(255) not null,
          status_envio               VARCHAR2(1) not null,
          cod_status_retorno         VARCHAR2(5),
          dsc_status_retorno         VARCHAR2(255),
          nro_protocolo              VARCHAR2(20),
          dta_registro_evento        DATE,
          created_at                 DATE default sysdate not null
        )
        tablespace TSD_POSEIDON
        ]';
  end if;
end;
/

-- ---------- COLUNAS (convergencia) ----------
declare
  qtd number;
begin
  for c in (
    select 'cod_dfe_cte_desacordo' as nome, q'[NUMBER generated by default as identity not null]' as def from dual union all
    select 'cod_dfe_cte', q'[NUMBER not null]' from dual union all
    select 'chave_cte', q'[VARCHAR2(44) not null]' from dual union all
    select 'usuario', q'[VARCHAR2(100) not null]' from dual union all
    select 'dsc_justificativa', q'[VARCHAR2(255) not null]' from dual union all
    select 'status_envio', q'[VARCHAR2(1) not null]' from dual union all
    select 'cod_status_retorno', q'[VARCHAR2(5)]' from dual union all
    select 'dsc_status_retorno', q'[VARCHAR2(255)]' from dual union all
    select 'nro_protocolo', q'[VARCHAR2(20)]' from dual union all
    select 'dta_registro_evento', q'[DATE]' from dual union all
    select 'created_at', q'[DATE default sysdate not null]' from dual
  ) loop
    begin
      select count(*) into qtd from all_tab_columns
       where owner = 'POSEIDON' and table_name = 'DPC_DFE_CTE_DESACORDO'
         and column_name = upper(c.nome);
      if qtd = 0 then
        execute immediate 'alter table poseidon.dpc_dfe_cte_desacordo add (' || c.nome || ' ' || c.def || ')';
        dbms_output.put_line('DPC_DFE_CTE_DESACORDO: acrescentada -> ' || c.nome);
      end if;
    exception
      when others then
        dbms_output.put_line('DPC_DFE_CTE_DESACORDO: FALHOU em ' || c.nome || ' -> ' || sqlerrm);
    end;
  end loop;
end;
/

