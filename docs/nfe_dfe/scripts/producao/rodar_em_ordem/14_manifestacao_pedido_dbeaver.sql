-- ===========================================================================
--  BLOCO 13_01 - PEDIDO DE MANIFESTACAO EM MASSA (fila com acompanhamento)
-- ===========================================================================
--
--  Banco: Oracle (homolog)        Schema: poseidon
--  Tabela nova:   poseidon.dpc_dfe_manif_pedido
--  Tabela alterada: poseidon.dpc_dfe_manifestacao (1 coluna, 1 FK, 1 indice)
--  Rollback: rollback/13_99_rollback_manifestacao_pedido_dbeaver.sql
--
--  ==========================================================================
--   POR QUE
--  ==========================================================================
--  A tela de NF-e manifesta no maximo 20 notas por vez (teto da SEFAZ por
--  lote). Na Qive a equipe fiscal manifesta ate 5.000 de uma vez, em segundo
--  plano, e fecha o backlog assim. Medido em 07/10/2026: 6.317 notas
--  escrituradas dentro do prazo de 90 dias ainda sem Confirmacao.
--
--  A fila usa o que ja existe: dpc_dfe_manifestacao aceita status_envio 'P'
--  desde a fundacao (default e CK1). O que faltava para ACOMPANHAR e este bloco.
--
--  ==========================================================================
--   POR QUE UMA TABELA DE PEDIDO, E NAO SO UMA COLUNA
--  ==========================================================================
--  So a coluna nas linhas de manifestacao nao conta a historia inteira: as
--  notas RECUSADAS na entrada (fora do prazo, ja manifestadas, sem acesso) nunca
--  viram linha, e o painel precisa dizer "pedi 5.000, aceitei 4.870, recusei
--  130". O cabecalho guarda quem pediu, quando, o evento, as tres contagens e
--  se foi cancelado. O andamento (quantas ja sairam) continua sendo CONTADO nas
--  linhas, nunca guardado: contador gravado diverge, contagem nao.
--
--  ==========================================================================
--   COMO O ACOMPANHAMENTO LE ISTO
--  ==========================================================================
--  Por pedido, contando dpc_dfe_manifestacao.status_envio:
--    P = na fila   E = enviada   F = falhou
--  Cancelar um pedido apaga SO as linhas P (nunca chegaram a SEFAZ) e marca o
--  cabecalho com status_pedido = 'C'.
--
--  ==========================================================================
--   SEM DEFAULT NA COLUNA NOVA
--  ==========================================================================
--  cod_dfe_manif_pedido e nula em toda manifestacao que nao veio de um pedido
--  (envio manual de ate 20 e agendador automatico). Sem DEFAULT, o Oracle nao
--  reescreve a tabela.
--
--  ==========================================================================
--   DEPOIS DESTE BLOCO
--  ==========================================================================
--  1. ajustes_unicos/2026-10-07_parametros_fila_manifestacao.sql (2 parametros).
--  2. Deploy da ApiNFE e da ApiDPC desta entrega. ANTES do bloco, a ApiDPC
--     da ORA-00904 na listagem de NF-e (a subquery de "Na fila" le a coluna).
--
--  ==========================================================================
--   ANTES DE RODAR: CONFIRA SE JA RODOU
--  ==========================================================================
--  Rode o SELECT do fim do arquivo. Se a tabela ja aparecer, nao rode de novo
--  (o create repetido da ORA-00955).
--
--  Sem bloco PL/SQL, pela regra do modulo: o divisor do DBeaver corta bloco e
--  o Oracle devolve PLS-00103.
--
--  Rodar no DBeaver com Execute script (Alt+X).
-- ===========================================================================


create table poseidon.dpc_dfe_manif_pedido
(
  cod_dfe_manif_pedido NUMBER generated by default as identity not null,
  cod_tipo_evento      VARCHAR2(6)   not null,
  usuario              VARCHAR2(100) not null,
  qtd_solicitada       NUMBER        not null,
  qtd_aceita           NUMBER        not null,
  qtd_recusada         NUMBER        not null,
  status_pedido        VARCHAR2(1) default 'A' not null,
  usuario_cancelamento VARCHAR2(100),
  dta_cancelamento     DATE,
  created_at           DATE default sysdate not null,
  constraint DPC_DFE_MANIF_PEDIDO_PK  primary key (cod_dfe_manif_pedido),
  constraint DPC_DFE_MANIF_PEDIDO_CK1 check (cod_tipo_evento in ('210210', '210200')),
  constraint DPC_DFE_MANIF_PEDIDO_CK2 check (status_pedido in ('A', 'C'))
)
tablespace TSD_POSEIDON;

comment on table poseidon.dpc_dfe_manif_pedido is
  'Pedido de manifestacao em massa (ate 5.000 notas), enviado em segundo plano pelo dfe:manifestar --fila. O andamento e CONTADO em dpc_dfe_manifestacao, nunca guardado aqui.';

comment on column poseidon.dpc_dfe_manif_pedido.cod_tipo_evento is
  'So Ciencia (210210) e Confirmacao (210200). Desconhecimento e Operacao nao realizada ficam so no envio manual de ate 20: declaram que a operacao nao ocorreu e nao tem volta.';

comment on column poseidon.dpc_dfe_manif_pedido.usuario is
  'Login de quem fez o pedido. Vem do token, nunca de parametro.';

comment on column poseidon.dpc_dfe_manif_pedido.qtd_solicitada is
  'Quantas chaves a pessoa mandou.';

comment on column poseidon.dpc_dfe_manif_pedido.qtd_aceita is
  'Quantas viraram linha na fila (status P). qtd_solicitada = qtd_aceita + qtd_recusada.';

comment on column poseidon.dpc_dfe_manif_pedido.qtd_recusada is
  'Recusadas na entrada (fora do prazo, ja manifestada, ja na fila, sem acesso). Nao viram linha: so esta contagem sobra.';

comment on column poseidon.dpc_dfe_manif_pedido.status_pedido is
  'A = ativo, C = cancelado. "Concluido" nao e status: e nao restar linha P no pedido.';

comment on column poseidon.dpc_dfe_manif_pedido.usuario_cancelamento is
  'Quem cancelou. Cancelar apaga so as linhas P; E e F ficam.';

alter table poseidon.dpc_dfe_manifestacao add (cod_dfe_manif_pedido NUMBER);

comment on column poseidon.dpc_dfe_manifestacao.cod_dfe_manif_pedido is
  'Pedido em massa de onde esta linha veio. Nulo no envio manual de ate 20 e no agendador automatico.';

alter table poseidon.dpc_dfe_manifestacao add constraint DPC_DFE_MANIF_FK2
  foreign key (cod_dfe_manif_pedido) references poseidon.dpc_dfe_manif_pedido (cod_dfe_manif_pedido);

create index poseidon.DPC_DFE_MANIF_IX2
  on poseidon.dpc_dfe_manifestacao (cod_dfe_manif_pedido, status_envio)
  tablespace TSD_POSEIDON;


