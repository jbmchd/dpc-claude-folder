-- ###########################################################################
--  3. NOMES DE CONSTRAINT E DE INDICE
-- ###########################################################################
--  As tabelas criadas a mao deixaram a PK com nome do sistema
--  (SYS_C00635357) e a unique com um padrao proprio (uq_sefaz_usr_emp). O
--  rename da tabela NAO renomeia nada disso - ficaria uma
--  dpc_dfe_usuario_empresa cuja PK ainda se chama SYS_C00635357 e cuja unique
--  ainda diz "sefaz".
--
--  Os blocos abaixo procuram a constraint PELO TIPO, e nao pelo nome antigo:
--  o nome gerado pelo sistema e DIFERENTE em cada banco, entao um script que
--  citasse SYS_C00635357 funcionaria em homologacao e falharia em producao.
--
--  Renomear constraint e indice nao e visivel ao codigo: o PHP so cita nome de
--  tabela e de coluna.

-- ---------- PK das tres ----------
declare
  v_atual  varchar2(128);
  v_idx    varchar2(128);
begin
  for t in (select 'DPC_DFE_USUARIO_EMPRESA' as tab, 'DPC_DFE_USUARIO_EMPRESA_PK' as novo from dual union all
            select 'DPC_DFE_USUARIO_ABA',           'DPC_DFE_USUARIO_ABA_PK'           from dual union all
            select 'DPC_DFE_PAINEL_ALERTA',         'DPC_DFE_PAINEL_ALERTA_PK'         from dual) loop
    begin
      select constraint_name, index_name
        into v_atual, v_idx
        from all_constraints
       where owner = 'POSEIDON' and table_name = t.tab and constraint_type = 'P';

      if v_atual <> t.novo then
        execute immediate 'alter table poseidon.' || t.tab
                       || ' rename constraint "' || v_atual || '" to ' || t.novo;
        dbms_output.put_line(t.tab || ': PK ' || v_atual || ' -> ' || t.novo);
      end if;

      if v_idx is not null and v_idx <> t.novo then
        execute immediate 'alter index poseidon."' || v_idx || '" rename to ' || t.novo;
        dbms_output.put_line(t.tab || ': indice da PK ' || v_idx || ' -> ' || t.novo);
      end if;
    exception
      when no_data_found then
        dbms_output.put_line(t.tab || ': sem PK ou tabela ausente - nada a fazer.');
      when others then
        dbms_output.put_line(t.tab || ': FALHOU no ajuste da PK -> ' || sqlerrm);
    end;
  end loop;
end;

-- ---------- UNIQUE das tres ----------
declare
  v_atual  varchar2(128);
  v_idx    varchar2(128);
begin
  for t in (select 'DPC_DFE_USUARIO_EMPRESA' as tab, 'DPC_DFE_USUARIO_EMPRESA_UK1' as novo from dual union all
            select 'DPC_DFE_USUARIO_ABA',           'DPC_DFE_USUARIO_ABA_UK1'           from dual union all
            select 'DPC_DFE_PAINEL_ALERTA',         'DPC_DFE_PAINEL_ALERTA_UK1'         from dual) loop
    begin
      select constraint_name, index_name
        into v_atual, v_idx
        from all_constraints
       where owner = 'POSEIDON' and table_name = t.tab and constraint_type = 'U';

      if v_atual <> t.novo then
        execute immediate 'alter table poseidon.' || t.tab
                       || ' rename constraint "' || v_atual || '" to ' || t.novo;
        dbms_output.put_line(t.tab || ': UK ' || v_atual || ' -> ' || t.novo);
      end if;

      if v_idx is not null and v_idx <> t.novo then
        execute immediate 'alter index poseidon."' || v_idx || '" rename to ' || t.novo;
        dbms_output.put_line(t.tab || ': indice da UK ' || v_idx || ' -> ' || t.novo);
      end if;
    exception
      when no_data_found then
        dbms_output.put_line(t.tab || ': sem UNIQUE ou tabela ausente - nada a fazer.');
      when others then
        dbms_output.put_line(t.tab || ': FALHOU no ajuste da UK -> ' || sqlerrm);
    end;
  end loop;
end;

-- ---------- o CHECK do aba ----------
--  So o de dpc_dfe_usuario_aba tem check nomeado (ck_sefaz_aba). Os demais
--  CHECK das tres tabelas sao os NOT NULL implicitos, gerados pelo Oracle -
--  esses ficam como estao, e o modulo tambem nao nomeia NOT NULL.
declare
  v_atual varchar2(128);
begin
  begin
    select constraint_name into v_atual
      from all_constraints
     where owner = 'POSEIDON' and table_name = 'DPC_DFE_USUARIO_ABA'
       and constraint_type = 'C' and constraint_name not like 'SYS%';

    if v_atual <> 'DPC_DFE_USUARIO_ABA_CK1' then
      execute immediate 'alter table poseidon.dpc_dfe_usuario_aba rename constraint "'
                     || v_atual || '" to DPC_DFE_USUARIO_ABA_CK1';
      dbms_output.put_line('DPC_DFE_USUARIO_ABA: CK ' || v_atual || ' -> DPC_DFE_USUARIO_ABA_CK1');
    end if;
  exception
    when no_data_found then
      dbms_output.put_line('DPC_DFE_USUARIO_ABA: sem check nomeado - nada a fazer.');
    when too_many_rows then
      dbms_output.put_line('DPC_DFE_USUARIO_ABA: MAIS DE UM check nomeado - resolva a mao.');
    when others then
      dbms_output.put_line('DPC_DFE_USUARIO_ABA: FALHOU no ajuste do CK -> ' || sqlerrm);
  end;
end;


