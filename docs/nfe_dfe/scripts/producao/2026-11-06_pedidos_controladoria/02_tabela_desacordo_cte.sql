create table poseidon.dpc_dfe_cte_desacordo
(
  cod_dfe_cte_desacordo      NUMBER generated by default as identity not null,
  cod_dfe_cte                NUMBER not null,
  chave_cte                  VARCHAR2(44) not null,
  usuario                    VARCHAR2(100) not null,
  dsc_justificativa          VARCHAR2(255) not null,
  status_envio               VARCHAR2(1) not null,
  cod_status_retorno         VARCHAR2(5),
  dsc_status_retorno         VARCHAR2(255),
  nro_protocolo              VARCHAR2(20),
  dta_registro_evento        DATE,
  created_at                 DATE default sysdate not null
)
tablespace TSD_POSEIDON;

alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_PK primary key (cod_dfe_cte_desacordo) using index tablespace TSD_POSEIDON;

alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_FK1 foreign key (cod_dfe_cte) references poseidon.dpc_dfe_cte (cod_dfe_cte);

alter table poseidon.dpc_dfe_cte_desacordo add constraint DPC_DFE_CTE_DESACORDO_CK1 check (status_envio in ('E', 'F'));

create index poseidon.DPC_DFE_CTE_DESACORDO_IDX1 on poseidon.dpc_dfe_cte_desacordo (chave_cte, status_envio) tablespace TSD_POSEIDON;

comment on table poseidon.dpc_dfe_cte_desacordo is
  'Trilha de auditoria do evento de Prestacao do Servico em Desacordo (610110) enviado pela tela de CT-e: quem mandou, a justificativa e o retorno da SEFAZ. O evento em si volta pela distribuicao e entra em dpc_dfe_cte_evento.';
comment on column poseidon.dpc_dfe_cte_desacordo.cod_dfe_cte_desacordo is
  'PK. IDENTITY COLUMN (generated by default as identity).';
comment on column poseidon.dpc_dfe_cte_desacordo.cod_dfe_cte is
  'FK para dpc_dfe_cte.';
comment on column poseidon.dpc_dfe_cte_desacordo.chave_cte is
  'Chave de acesso do CT-e (44 digitos), copiada para consultar sem join.';
