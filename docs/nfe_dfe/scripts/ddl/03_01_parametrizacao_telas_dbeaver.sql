  qtd_antigo number;
  qtd_novo   number;
begin
  select count(*) into qtd_antigo from all_tables
   where owner = 'POSEIDON' and table_name = 'DPC_SEFAZ_USUARIO_EMPRESA';
  select count(*) into qtd_novo from all_tables
   where owner = 'POSEIDON' and table_name = 'DPC_DFE_USUARIO_EMPRESA';

  if qtd_antigo = 1 and qtd_novo = 0 then
    execute immediate 'alter table poseidon.dpc_sefaz_usuario_empresa rename to dpc_dfe_usuario_empresa';
    dbms_output.put_line('renomeada: dpc_sefaz_usuario_empresa -> dpc_dfe_usuario_empresa');
  elsif qtd_antigo = 1 and qtd_novo = 1 then
    dbms_output.put_line('ATENCAO: as DUAS existem. Nada foi feito - resolva a mao qual vale.');
  elsif qtd_novo = 1 then
    dbms_output.put_line('dpc_dfe_usuario_empresa ja esta com o nome novo.');
  else
    dbms_output.put_line('nenhuma das duas existe - a secao 2 vai criar.');
  end if;
end;

